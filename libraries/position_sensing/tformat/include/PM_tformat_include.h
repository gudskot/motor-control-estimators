typedef struct PM_tformat_DataStruct {
    uint16_t  controlField;
    uint16_t  statusField;
    uint16_t  dataField0;
    uint16_t  dataField1;
    uint16_t  dataField2;
    uint16_t  dataField3;
    uint16_t  dataField4;
    uint16_t  dataField5;
    uint16_t  dataField6;
    uint16_t  dataField7;
    uint16_t  crcField;
    uint16_t  crcCheck;
    uint16_t  eepromAddressField;
    uint16_t  eepromWrDataField;
    uint16_t  eepromRdDataField;
    volatile bool  dataReady;
    uint16_t  fifoLevel;
} PM_tformat_DataStruct;

