//*****************************************************************************
//
// Command fields and expected response fields for each Data ID code.
// Each field is 10-bits including start (1-bit) and delimiter (1-bit)
// Abbreviations are from the T-Format specification:
//
//      CF:     Control Field
//      SF:     Status Field
//      DFx:    Data Field
//      CRC:    Cyclic-redundancy check Field
//      ABSx:   Absolute data in 1 revolution
//      ABMx:   Multi-turn data
//      ADF:    Address data field
//      EDF:    EEPROM data field
//      ENID:   Encoder ID
//      ALMC:   Encoder error
//
// [doc-library-tformat-command-format-start]
//
// Transmit packet (request)
//      Number of 10-bit fields (command) for each Data ID code:
//
//      ID0: TX 1 field    CF
//      ID1: TX 1 field    CF
//      ID2: TX 1 field    CF
//      ID3: TX 1 field    CF
//      ID7: TX 1 field    CF
//      ID8: TX 1 field    CF
//      IDC: TX 1 field    CF
//      ID6: TX 4 fields   CF + ADF + EDF + CRC      (EEPROM write)
//      IDD: TX 3 fields   CF + ADF + CRC            (EEPROM read)
//
// Receive packet (response)
//      Number of 10-bit fields received for each request
//
//      ID0: RX 6 fields:  CF + SF + DF0 + DF1 + DF2 + CRC
//                                   DF0-DF2 == ABS0-ABS2
//
//      ID1: RX 6 fields:  CF + SF + DF0 + DF1 + DF2 + CRC
//                                   DF0-DF2 == ABM0-ABM2
//
//      ID2: RX 4 fields:  CF + SF + DF0 + CRC
//                                   DF0 == ENID
//
//      ID3: RX 11 fields: CF + SF + DF0 + DF1 + DF2....DF7 + CRC
//                                   DF0-DF2 == ABS0-ABS2
//                                   DF3 == ENID
//                                   DF4-DF6 == ABM0-ABM2
//                                   DF7 == ALMC
//
//      ID7: RX 6 fields:  CF + SF + DF0 + DF1 + DF2 + CRC
//                                   DF0-DF2 == ABS0-ABS2
//
//      ID8: RX 6 fields:  CF + SF + DF0 + DF1 + DF2 + CRC
//                                   DF0-DF2 == ABS0-ABS2
//
//      IDC: RX 6 fields:  CF + SF + DF0 + DF1 + DF2 + CRC
//                                   DF0-DF2 == ABS0-ABS2
//
//      ID6: RX 4 fields:  CF + ADF + EDF + CRC
//
//      IDD: RX 4 fields:  CF + ADF + EDF + CRC
//
//*****************************************************************************
#define PM_TFORMAT_TX_FIELDS_ID0    1u
#define PM_TFORMAT_TX_FIELDS_ID1    1u
#define PM_TFORMAT_TX_FIELDS_ID2    1u
#define PM_TFORMAT_TX_FIELDS_ID3    1u
#define PM_TFORMAT_TX_FIELDS_ID7    1u
#define PM_TFORMAT_TX_FIELDS_ID8    1u
#define PM_TFORMAT_TX_FIELDS_IDC    1u
#define PM_TFORMAT_TX_FIELDS_ID6    4u
#define PM_TFORMAT_TX_FIELDS_IDD    3u

#define PM_TFORMAT_RX_FIELDS_ID0    6u
#define PM_TFORMAT_RX_FIELDS_ID1    6u
#define PM_TFORMAT_RX_FIELDS_ID2    4u
#define PM_TFORMAT_RX_FIELDS_ID3    11u
#define PM_TFORMAT_RX_FIELDS_ID7    6u
#define PM_TFORMAT_RX_FIELDS_ID8    6u
#define PM_TFORMAT_RX_FIELDS_IDC    6u
#define PM_TFORMAT_RX_FIELDS_ID6    4u
#define PM_TFORMAT_RX_FIELDS_IDD    4u

#define PM_TFORMAT_RX_FIELDS_MAX    11u
#define PM_TFORMAT_TX_FIELDS_MAX     4u
#define PM_TFORMAT_FIELDS_MAX                                                  \
